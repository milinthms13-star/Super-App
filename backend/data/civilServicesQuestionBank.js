/**
 * Get Civil Services questions by level, subject, and difficulty
 */
function getCivilServicesQuestions(level, subject, difficulty) {
  const levelBank = civilServicesQuestionBank[level];
  if (!levelBank) return [];

  const subjectBank = levelBank[subject];
  if (!subjectBank) return [];

  return subjectBank[difficulty] || [];
}

/**
 * Get all subjects for a level
 */
function getCivilServicesSubjects(level) {
  const levelBank = civilServicesQuestionBank[level];
  if (!levelBank) return [];

  return Object.keys(levelBank);
}

/**
 * Get all levels
 */
function getCivilServicesLevels() {
  return Object.keys(civilServicesQuestionBank);
}


// Helper function to get translation
export const getTranslation = (lang, key) => {
  const keys = key.split(".");
  let value = healthcareTranslations[lang] || healthcareTranslations.en;
  
  for (const k of keys) {
    value = value?.[k];
    if (!value) {
      // Fallback to English
      value = healthcareTranslations.en;
      for (const fallbackKey of keys) {
        value = value?.[fallbackKey];
        if (!value) return key;
      }
      break;
    }
  }
  
  return value || key;
};

export default healthcareTranslations;
